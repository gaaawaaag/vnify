import {readFile,writeFile,mkdir,stat} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {readPromptLibrary,renderPromptFrom,promptRecipeFrom} from '../src/prompts/format.js';
import {isBookLanguage,BOOK_LANGUAGES} from '../src/core/language.js';

const root=fileURLToPath(new URL('../',import.meta.url));
const base=path.join(root,'docs/prompts_v3');
const generated=path.join(root,'src/prompts/library.generated.js');
const usage='node scripts/prompts.mjs --build | --check [--candidate <目录>] | --recipe <名称> [--lang zh|zh-Hant|en|ja] [--candidate <目录>] --out <文件> | --fragment <ID> [--values <JSON文件>] [--lang zh|zh-Hant|en|ja] [--candidate <目录>] --out <文件>';
try {
  const args=process.argv.slice(2),options={};
  if(args[0]==='--help'){console.log(usage);process.exit(0);}
  while(args.length){const key=args.shift();if(!['--build','--check','--candidate','--recipe','--fragment','--values','--out','--lang'].includes(key)||key in options)throw new Error(usage);options[key]=['--build','--check'].includes(key)?true:args.shift();if(!options[key]||String(options[key]).startsWith('--'))throw new Error(usage);}
  if(['--build','--check','--recipe','--fragment'].filter(k=>options[k]).length!==1)throw new Error(usage);
  const lang=options['--lang'];
  if(lang!==undefined&&!isBookLanguage(lang))throw new Error(`--lang 须为 ${BOOK_LANGUAGES.join('／')}。`);
  if(options['--build']&&(options['--candidate']||options['--out']))throw new Error('候选稿只检查／预览，不覆盖运行目录。应用时先将审核后的模块复制回 prompts_v3。');
  const candidate=options['--candidate']?path.resolve(options['--candidate']):null;
  if(candidate&&!(await stat(candidate)).isDirectory())throw new Error('候选路径需要已有目录。');
  const read=async relative=>{
    if(candidate){try{return await readFile(path.join(candidate,relative),'utf8');}catch(error){if(error.code!=='ENOENT')throw error;}}
    return readFile(path.join(base,relative),'utf8');
  };
  const library=await readPromptLibrary(read);
  const output='// Generated by node scripts/prompts.mjs --build. Edit docs/prompts_v3, not this file.\nexport const PROMPT_LIBRARY = '+JSON.stringify(library,null,2)+';\n';
  if(options['--build']){await writeFile(generated,output);console.log(`已编译 ${Object.keys(library.texts).length} 个提示词片段／组合。`);}
  else if(options['--check']) {
    if(candidate){
      const original=await readPromptLibrary(relative=>readFile(path.join(base,relative),'utf8'));
      const changed=[...new Set([...Object.keys(original.texts),...Object.keys(library.texts)])].filter(id=>original.texts[id]!==library.texts[id]);
      console.log(JSON.stringify({ok:true,candidate,changed:changed.map(id=>({id,source:library.sources[id],before:original.texts[id]?.length??0,after:library.texts[id]?.length??0})),note:'通过表示模块与占位符可组装；不代表新文字符合 VN 协议或语义质量已验收。'},null,2));
    }else{if((await readFile(generated,'utf8')).replace(/\r\n?/g,'\n')!==output)throw new Error('提示词编译产物已过期，请运行 npm run prompts:build。');console.log('提示词模块、占位符、配方及编译产物一致。');}
  }else {
    if(!options['--out'])throw new Error(usage);
    const target=path.resolve(options['--out']);
    const inside=(dir,file)=>{const rel=path.relative(dir,file);return !rel.startsWith('..')&&!path.isAbsolute(rel);};
    if(inside(base,target)||target===generated||(candidate&&inside(candidate,target)))throw new Error('预览输出须与正式模块及候选目录分开。');
    const values=options['--values']?JSON.parse(await readFile(options['--values'],'utf8')):{};
    const text=options['--recipe']?promptRecipeFrom(library,options['--recipe'],lang):renderPromptFrom(library,options['--fragment'],values,lang);
    await mkdir(path.dirname(target),{recursive:true});await writeFile(target,text);console.log(target);
  }
}catch(error){console.error(error.message);process.exitCode=1;}
